const tenantAssignablePermissionCodeSet = new Set<string>(
  TENANT_ASSIGNABLE_PERMISSION_CODES,
);
const platformOnlyPermissionCodeSet = new Set<string>(
  PLATFORM_ONLY_PERMISSION_CODES,
);

export function isTenantAssignablePermission(code: string): boolean {
  return tenantAssignablePermissionCodeSet.has(code);
}

export function isPlatformOnlyPermission(code: string): boolean {
  return platformOnlyPermissionCodeSet.has(code);
}
