"use client"

import React from "react"
import { useQuery } from "@tanstack/react-query"

import { MetricCard, PageHeader, SectionHeader, StatusBadge, UnavailableState } from "@/components/data-display/states"
import { getAnalyticsSummary, getTopProducts, analyticsKeys } from "@/features/erp/analytics/api/queries"
import { useAuthStore } from "@/stores/auth.store"
import { hasPermission } from "@/lib/permissions"

function formatCurrency(value: number) {
  return new Intl.NumberFormat("en-US", { maximumFractionDigits: 0 }).format(value)
}

export default function DashboardPage() {
  const token = useAuthStore((state) => state.accessToken)
  const session = useAuthStore((state) => state.session)
  const tenantId = session?.tenantId
  const canRead = hasPermission(session, "analytics.read")

  const summaryQuery = useQuery({
    queryKey: tenantId ? analyticsKeys.summary(tenantId) : ["analytics", "unauthenticated", "summary"],
    queryFn: () => getAnalyticsSummary(token as string),
    enabled: Boolean(token && tenantId && canRead),
    staleTime: 60_000,
  })

  const topProductsQuery = useQuery({
    queryKey: tenantId ? analyticsKeys.topProducts(tenantId) : ["analytics", "unauthenticated", "top-products"],
    queryFn: () => getTopProducts(token as string),
    enabled: Boolean(token && tenantId && canRead),
    staleTime: 60_000,
  })

  if (!canRead) {
    return <UnavailableState title="Analytics access is restricted" description="Your current tenant session does not include the analytics.read permission." />
  }

  if (!token || !tenantId) {
    return <UnavailableState title="Analytics is unavailable" description="Sign in to load tenant analytics from the verified backend summary contract." />
  }

  if (summaryQuery.isPending || topProductsQuery.isPending) {
    return (
      <>
        <PageHeader eyebrow="Tenant application" title="Operations dashboard" description="Verified backend analytics for the active tenant." />
        <div className="grid gap-4 md:grid-cols-2 xl:grid-cols-4">
          {Array.from({ length: 4 }).map((_, index) => (
            <div key={index} className="h-32 animate-pulse rounded-[22px] border border-border bg-card" />
          ))}
        </div>
      </>
    )
  }

  if (summaryQuery.isError || topProductsQuery.isError) {
    const message = summaryQuery.error instanceof Error || topProductsQuery.error instanceof Error
      ? "The analytics API is unavailable or rejected this request. No fabricated KPI values are shown."
      : "The analytics API is unavailable or rejected this request. No fabricated KPI values are shown."
    return <UnavailableState title="Unable to load analytics" description={message} />
  }

  const summary = summaryQuery.data
  const topProducts = topProductsQuery.data?.items ?? []

  return (
    <>
      <PageHeader
        eyebrow="Tenant application"
        title="Operations dashboard"
        description="Verified tenant analytics generated by the backend summary and top-products endpoints."
        actions={<StatusBadge tone="info">Backend-backed KPI</StatusBadge>}
      />

      <section className="grid gap-4 md:grid-cols-2 xl:grid-cols-4">
        <MetricCard title="Total revenue" value={formatCurrency(summary.totalRevenue)} detail="Paid payment total returned by analytics summary" tone="success" />
        <MetricCard title="Total orders" value={String(summary.totalOrders)} detail="Orders in the active tenant scope" tone="info" />
        <MetricCard title="Paid orders" value={String(summary.paidOrders)} detail="Orders currently counted as paid" tone="success" />
        <MetricCard title="Avg order value" value={formatCurrency(summary.averageOrderValue)} detail="Derived by backend summary" tone="warning" />
      </section>

      <div className="mt-8 grid gap-6 xl:grid-cols-[1.4fr_0.9fr]">
        <section className="rounded-3xl border border-border bg-card p-5 shadow-[0_10px_30px_rgba(15,23,42,0.03)]">
          <SectionHeader eyebrow="Summary" title="Order and payment status" />
          <div className="mt-4 grid gap-3 sm:grid-cols-2">
            <MetricCard title="Completed orders" value={String(summary.completedOrders)} detail="Completed status count" tone="success" />
            <MetricCard title="Pending orders" value={String(summary.pendingOrders)} detail="Pending status count" tone="warning" />
            <MetricCard title="Cancelled orders" value={String(summary.cancelledOrders)} detail="Cancelled status count" tone="danger" />
            <MetricCard title="Total payments" value={String(summary.totalPayments)} detail="Payment transactions in scope" tone="info" />
          </div>
        </section>

        <section className="rounded-3xl border border-border bg-card p-5 shadow-[0_10px_30px_rgba(15,23,42,0.03)]">
          <SectionHeader eyebrow="Catalog" title="Top products" />
          {topProducts.length ? (
            <div className="mt-4 space-y-3">
              {topProducts.map((item, index) => (
                <div key={item.productId} className="flex items-center justify-between rounded-2xl border border-border bg-[var(--panel-alt)] px-4 py-3">
                  <div>
                    <p className="text-[10px] font-bold uppercase tracking-[0.2em] text-[var(--muted-foreground)]">#{index + 1}</p>
                    <p className="mt-1 font-medium text-[var(--foreground)]">{item.name}</p>
                  </div>
                  <StatusBadge tone="info">{item.qtySold} sold</StatusBadge>
                </div>
              ))}
            </div>
          ) : (
            <div className="mt-4 rounded-2xl border border-dashed border-[var(--border)] bg-[var(--muted)]/30 p-4 text-sm text-[var(--muted-foreground)]">
              No top-product data is available from the backend for the active scope.
            </div>
          )}
        </section>
      </div>
    </>
  )
}
